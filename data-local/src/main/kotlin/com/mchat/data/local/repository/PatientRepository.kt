package com.mchat.data.local.repository

import androidx.room.withTransaction
import com.mchat.core.common.ClockProvider
import com.mchat.data.local.dao.PatientDao
import com.mchat.data.local.dao.SystemDao
import com.mchat.data.local.db.MChatDatabase
import com.mchat.data.local.entity.AppSettingsEntity
import com.mchat.data.local.entity.CaregiverEntity
import com.mchat.data.local.entity.ConsentRecordEntity
import com.mchat.data.local.entity.PatientEntity
import com.mchat.domain.scoring.model.SyncStatus
import kotlinx.coroutines.flow.Flow
import java.util.UUID
import javax.inject.Inject
import javax.inject.Singleton

data class PatientRegistrationInput(
  val patientCode: String?,
  val fullName: String,
  val dateOfBirthIso: String,
  val sex: String,
  val extraFieldsJson: String,
  val clinicalNotes: String?,
  val caregiverName: String,
  val caregiverRelationship: String,
  val caregiverPhone: String?,
  val caregiverEmail: String?,
  val consentedByName: String,
  val consentedByRelationship: String,
  val consentScope: String,
  val consentTextVersion: String = "v1.0",
)

sealed interface PatientSaveResult {
  data class Success(val patientId: String, val consentId: String) : PatientSaveResult
  data class DuplicateCode(val existingCode: String) : PatientSaveResult
}

@Singleton
class PatientRepository @Inject constructor(
  private val database: MChatDatabase,
  private val patientDao: PatientDao,
  private val systemDao: SystemDao,
  private val auditRepository: AuditRepository,
  private val clockProvider: ClockProvider,
) {
  fun observeActivePatients(): Flow<List<PatientEntity>> = patientDao.observePatients(archived = false)
  fun observeArchivedPatients(): Flow<List<PatientEntity>> = patientDao.observePatients(archived = true)
  fun observePatientById(id: String): Flow<PatientEntity?> = patientDao.observePatientById(id)
  fun observeCaregivers(patientId: String): Flow<List<CaregiverEntity>> =
    patientDao.observeCaregiversForPatient(patientId)
  fun observeConsents(patientId: String): Flow<List<ConsentRecordEntity>> =
    patientDao.observeConsentsForPatient(patientId)
  fun observeActivePatientCount(): Flow<Int> = patientDao.observeActivePatientCount()

  suspend fun getPatientById(id: String): PatientEntity? = patientDao.getPatientById(id)
  suspend fun getLatestActiveConsent(patientId: String): ConsentRecordEntity? =
    patientDao.getLatestActiveConsent(patientId)
  suspend fun getPrimaryCaregiver(patientId: String): CaregiverEntity? =
    patientDao.getPrimaryCaregiver(patientId)

  suspend fun isCodeDuplicate(code: String, excludePatientId: String? = null): Boolean {
    val existing = patientDao.getPatientByCode(code.trim()) ?: return false
    return existing.id != excludePatientId
  }

  suspend fun generateNextPatientCode(): String {
    val settings = systemDao.getAppSettings() ?: AppSettingsEntity(updatedAt = clockProvider.nowEpochMillis())
    var seq = settings.nextPatientCodeSeq
    var candidate = "${settings.patientCodePrefix}%04d".format(seq)
    while (patientDao.getPatientByCode(candidate) != null) {
      seq++
      candidate = "${settings.patientCodePrefix}%04d".format(seq)
    }
    return candidate
  }

  suspend fun registerPatientWithConsent(input: PatientRegistrationInput): PatientSaveResult {
    val now = clockProvider.nowEpochMillis()
    val rawCode = input.patientCode?.trim().orEmpty()
    val isAuto = rawCode.isBlank()
    val resolvedCode = if (isAuto) generateNextPatientCode() else rawCode

    if (patientDao.getPatientByCode(resolvedCode) != null) {
      return PatientSaveResult.DuplicateCode(resolvedCode)
    }

    val patientId = UUID.randomUUID().toString()
    val caregiverId = UUID.randomUUID().toString()
    val consentId = UUID.randomUUID().toString()

    database.withTransaction {
      val settings = systemDao.getAppSettings() ?: AppSettingsEntity(updatedAt = now)
      if (isAuto) {
        systemDao.upsertAppSettings(
          settings.copy(nextPatientCodeSeq = settings.nextPatientCodeSeq + 1, updatedAt = now),
        )
      }

      patientDao.insertPatient(
        PatientEntity(
          id = patientId,
          patientCode = resolvedCode,
          isAutoGeneratedCode = isAuto,
          fullName = input.fullName.trim(),
          dateOfBirth = input.dateOfBirthIso.trim(),
          sex = input.sex,
          extraFieldsJson = input.extraFieldsJson,
          clinicalNotes = input.clinicalNotes?.trim()?.ifBlank { null },
          isArchived = false,
          syncStatus = SyncStatus.PENDING_SYNC,
          recordVersion = 1,
          createdAt = now,
          updatedAt = now,
        ),
      )

      patientDao.upsertCaregiver(
        CaregiverEntity(
          id = caregiverId,
          patientId = patientId,
          fullName = input.caregiverName.trim(),
          relationship = input.caregiverRelationship.trim(),
          phone = input.caregiverPhone?.trim()?.ifBlank { null },
          email = input.caregiverEmail?.trim()?.ifBlank { null },
          isPrimary = true,
          createdAt = now,
          updatedAt = now,
        ),
      )

      patientDao.upsertConsent(
        ConsentRecordEntity(
          id = consentId,
          patientId = patientId,
          caregiverId = caregiverId,
          consentedByName = input.consentedByName.trim(),
          consentedByRelationship = input.consentedByRelationship.trim(),
          consentScope = input.consentScope,
          consentTextVersion = input.consentTextVersion,
          consentedAt = now,
          createdAt = now,
        ),
      )
    }

    auditRepository.recordEvent(
      eventType = AuditEventType.CONSENT,
      entityType = "CONSENT",
      entityId = consentId,
      metadataJson = "{\"patientId\":\"$patientId\",\"scope\":\"${input.consentScope}\"}",
    )
    auditRepository.recordEvent(
      eventType = AuditEventType.CREATE,
      entityType = "PATIENT",
      entityId = patientId,
      metadataJson = "{\"autoCode\":$isAuto}",
    )

    return PatientSaveResult.Success(patientId = patientId, consentId = consentId)
  }

  suspend fun updatePatient(
    existing: PatientEntity,
    newCode: String,
    fullName: String,
    dateOfBirthIso: String,
    sex: String,
    extraFieldsJson: String,
    clinicalNotes: String?,
  ): PatientSaveResult {
    val trimmedCode = newCode.trim()
    if (isCodeDuplicate(trimmedCode, excludePatientId = existing.id)) {
      return PatientSaveResult.DuplicateCode(trimmedCode)
    }
    val now = clockProvider.nowEpochMillis()
    patientDao.updatePatient(
      existing.copy(
        patientCode = trimmedCode,
        fullName = fullName.trim(),
        dateOfBirth = dateOfBirthIso.trim(),
        sex = sex,
        extraFieldsJson = extraFieldsJson,
        clinicalNotes = clinicalNotes?.trim()?.ifBlank { null },
        syncStatus = SyncStatus.PENDING_SYNC,
        recordVersion = existing.recordVersion + 1,
        updatedAt = now,
      ),
    )
    auditRepository.recordEvent(
      eventType = AuditEventType.EDIT,
      entityType = "PATIENT",
      entityId = existing.id,
      metadataJson = "{\"version\":${existing.recordVersion + 1}}",
    )
    return PatientSaveResult.Success(existing.id, "")
  }

  suspend fun setPatientArchived(patientId: String, archived: Boolean) {
    val now = clockProvider.nowEpochMillis()
    patientDao.setPatientArchived(
      id = patientId,
      archived = archived,
      archivedAt = if (archived) now else null,
      updatedAt = now,
    )
    auditRepository.recordEvent(
      eventType = AuditEventType.ARCHIVE,
      entityType = "PATIENT",
      entityId = patientId,
      metadataJson = "{\"archived\":$archived}",
    )
  }
}
