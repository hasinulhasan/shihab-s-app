package com.mchat.data.local.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import com.mchat.domain.scoring.model.SyncStatus
import kotlinx.serialization.Serializable

@Serializable
@Entity(
  tableName = "patients",
  indices = [
    Index(value = ["patient_code"], unique = true),
    Index(value = ["is_archived", "updated_at"]),
    Index(value = ["full_name"]),
    Index(value = ["sync_status"]),
  ],
)
data class PatientEntity(
  @PrimaryKey val id: String,
  @ColumnInfo(name = "patient_code") val patientCode: String,
  @ColumnInfo(name = "is_auto_generated_code") val isAutoGeneratedCode: Boolean,
  @ColumnInfo(name = "full_name") val fullName: String,
  @ColumnInfo(name = "date_of_birth") val dateOfBirth: String,
  @ColumnInfo(name = "sex") val sex: String,
  @ColumnInfo(name = "extra_fields_json") val extraFieldsJson: String = "{}",
  @ColumnInfo(name = "clinical_notes") val clinicalNotes: String? = null,
  @ColumnInfo(name = "is_archived") val isArchived: Boolean = false,
  @ColumnInfo(name = "archived_at") val archivedAt: Long? = null,
  @ColumnInfo(name = "sync_status") val syncStatus: SyncStatus = SyncStatus.PENDING_SYNC,
  @ColumnInfo(name = "record_version") val recordVersion: Int = 1,
  @ColumnInfo(name = "created_at") val createdAt: Long,
  @ColumnInfo(name = "updated_at") val updatedAt: Long,
)

@Serializable
@Entity(
  tableName = "caregivers",
  foreignKeys = [
    ForeignKey(
      entity = PatientEntity::class,
      parentColumns = ["id"],
      childColumns = ["patient_id"],
      onDelete = ForeignKey.RESTRICT,
    ),
  ],
  indices = [
    Index(value = ["patient_id"]),
    Index(value = ["patient_id", "is_primary"]),
  ],
)
data class CaregiverEntity(
  @PrimaryKey val id: String,
  @ColumnInfo(name = "patient_id") val patientId: String,
  @ColumnInfo(name = "full_name") val fullName: String,
  @ColumnInfo(name = "relationship") val relationship: String,
  @ColumnInfo(name = "phone") val phone: String? = null,
  @ColumnInfo(name = "email") val email: String? = null,
  @ColumnInfo(name = "is_primary") val isPrimary: Boolean = true,
  @ColumnInfo(name = "created_at") val createdAt: Long,
  @ColumnInfo(name = "updated_at") val updatedAt: Long,
)

@Serializable
@Entity(
  tableName = "consent_records",
  foreignKeys = [
    ForeignKey(
      entity = PatientEntity::class,
      parentColumns = ["id"],
      childColumns = ["patient_id"],
      onDelete = ForeignKey.RESTRICT,
    ),
    ForeignKey(
      entity = CaregiverEntity::class,
      parentColumns = ["id"],
      childColumns = ["caregiver_id"],
      onDelete = ForeignKey.RESTRICT,
    ),
  ],
  indices = [
    Index(value = ["patient_id"]),
    Index(value = ["caregiver_id"]),
    Index(value = ["consented_at"]),
  ],
)
data class ConsentRecordEntity(
  @PrimaryKey val id: String,
  @ColumnInfo(name = "patient_id") val patientId: String,
  @ColumnInfo(name = "caregiver_id") val caregiverId: String? = null,
  @ColumnInfo(name = "consented_by_name") val consentedByName: String,
  @ColumnInfo(name = "consented_by_relationship") val consentedByRelationship: String,
  @ColumnInfo(name = "consent_scope") val consentScope: String,
  @ColumnInfo(name = "consent_text_version") val consentTextVersion: String,
  @ColumnInfo(name = "consented_at") val consentedAt: Long,
  @ColumnInfo(name = "is_withdrawn") val isWithdrawn: Boolean = false,
  @ColumnInfo(name = "withdrawn_at") val withdrawnAt: Long? = null,
  @ColumnInfo(name = "notes") val notes: String? = null,
  @ColumnInfo(name = "created_at") val createdAt: Long,
)
